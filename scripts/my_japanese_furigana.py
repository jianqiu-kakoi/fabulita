PARTICLES = set("をがはにでともへのやかよね")
BREAKS = set(" 　、。，．！？!?「」『』（）()→・／/：:；;…～〜＋+＝=|｜")


def segments(text: str) -> list[tuple[str, str | None]]:
    """Split text into (surface, markup-or-None); same algorithm as the page."""
    out: list[tuple[str, str | None]] = []
    keys = sorted(F, key=len, reverse=True)
    i, boundary = 0, True
    while i < len(text):
        ch = text[i]
        if ch in BREAKS or not ("\u3040" <= ch <= "\u30ff"):
            out.append((ch, None)); i += 1; boundary = True; continue
        if boundary:
            hit = next((k for k in keys if text.startswith(k, i)), None)
            if hit:
                out.append((hit, F[hit] if F[hit] != hit else None)); i += len(hit); boundary = True; continue
            if ch in PARTICLES:
                out.append((ch, None)); i += 1; boundary = True; continue
        out.append((ch, None)); i += 1; boundary = False
    return out


def render(text: str) -> str:
    """Plain-text preview: 働[はたら]き — for review only."""
    import re
    parts = []
    for surface, markup in segments(text):
        parts.append(re.sub(r"\{([^|}]+)\|([^}]+)\}", r"\1[\2]", markup) if markup else surface)
    return "".join(parts)


def used_keys(texts) -> dict[str, str]:
    used: dict[str, str] = {}
    for text in texts:
        for surface, markup in segments(text):
            if markup:
                used[surface] = markup
    return used
