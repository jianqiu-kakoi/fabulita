"""Kana → kanji-with-furigana display table for the My Japanese practice.

Answers and options stay in kana (scoring and saved progress do not change);
the page only *displays* matched words as <ruby>kanji<rt>reading</rt></ruby>.
Markup "{漢字|かな}" marks one ruby span; okurigana stays outside the braces.

Matching rules (mirrored in the page template):
- a key only matches at a word start: string start, after a space or
  punctuation, right after another matched word, or after a lone particle;
- the longest key wins;
- a value equal to its key is a blocker: it keeps a kana run (ください,
  います, によると...) from being split into a wrong match.
Ambiguous kana (かえる, かい, いき...) are only listed in unambiguous forms.
"""

F: dict[str, str] = {}


def add(markup: str, *kana: str) -> None:
    for key in kana:
        F[key] = markup if markup else key


def verb(kanji: str, reading: str, *endings: str) -> None:
    """One kanji + reading, followed by each okurigana ending: verb("書", "か", "く", "き") → かく, かき."""
    for ending in endings:
        F[reading + ending] = "{" + kanji + "|" + reading + "}" + ending


